                  w.SendToClientDate IS NOT NULL OR
                  w.SendToDoctorDate IS NOT NULL OR
                  w.SendToOrgDate IS NOT NULL OR
                  w.SendToFax IS NOT NULL
             THEN 1 ELSE 0 END AS Is_Print
    FROM Works w WITH (NOLOCK)
