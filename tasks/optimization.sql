                WHERE a.ID_ANALIZ = wi.ID_ANALIZ
                AND a.is_group = 1
            )
        ) AS WorkItemsNotComplit,
        (
            SELECT COUNT(*)
            FROM WorkItem wi WITH (NOLOCK)
            WHERE wi.Id_Work = w.Id_Work
            AND wi.is_complit = 1
            AND NOT EXISTS (
                SELECT 1
                FROM Analiz a WITH (NOLOCK)
                WHERE a.ID_ANALIZ = wi.ID_ANALIZ
                AND a.is_group = 1
            )
        ) AS WorkItemsComplit,
        ISNULL(e.SURNAME, '') + ' ' +
